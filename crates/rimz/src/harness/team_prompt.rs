//! The team prompt layer: the consensus and team-level prompt files a staged
//! team composes after every role's own system prompt, and the inspection
//! copy of the built-in consensus RimZ publishes beside the team definitions.

use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::config::Team;

/// The consensus every staged team runs under unless `consensus-file` replaces it.
pub const BUILT_IN_CONSENSUS: &str = include_str!("team_consensus.md");

/// The consensus piece a team listing `reflect` receives when no home or pack
/// trait claims that name.
pub const SHIPPED_REFLECT: &str = include_str!("team_reflect.md");

/// Where the inspection copy of [`SHIPPED_REFLECT`] lives under `agents_home`,
/// and the origin a team's prompt layer names for it. It stays out of
/// `traits/`, where a copy would itself replace the piece it shows.
pub fn reflect_copy_path(agents_home: &Path) -> PathBuf {
    agents_home
        .join("teams")
        .join("consensus")
        .join("reflect.md")
}

/// Where the inspection copy of [`BUILT_IN_CONSENSUS`] lives under
/// `agents_home`. The team definitions loader skips this path, so no Markdown
/// team can be named `consensus`.
pub fn consensus_copy_path(agents_home: &Path) -> PathBuf {
    agents_home.join("teams").join("consensus.md")
}

/// Publish the read-only inspection copies of the embedded consensus and the
/// shipped `reflect` piece. Nothing reads them back: teams always run under the
/// embedded text, so each copy is generated output and rewriting a stale or
/// edited one loses nothing. Returns the paths it wrote; a current copy is
/// left alone.
pub fn publish_consensus_copy(
    agents_home: &Path,
) -> Result<Vec<PathBuf>, crate::disk::atomic::AtomicErr> {
    let mut written = Vec::new();
    for (path, bytes) in [
        (consensus_copy_path(agents_home), consensus_copy_text()),
        (reflect_copy_path(agents_home), reflect_copy_text()),
    ] {
        if std::fs::read(&path).is_ok_and(|current| current == bytes.as_bytes()) {
            continue;
        }
        crate::disk::atomic::write_bytes_atomically(&path, bytes.as_bytes())?;
        written.push(path);
    }
    Ok(written)
}

fn consensus_copy_text() -> String {
    format!(
        "<!-- Generated by rimz {}. A read-only copy of the built-in team consensus: \
         RimZ never reads this file, so edits change nothing and are overwritten. \
         To replace it, set `consensus-file` on a project TOML team. -->\n\n{BUILT_IN_CONSENSUS}",
        crate::build_id::VERSION
    )
}

fn reflect_copy_text() -> String {
    format!(
        "<!-- Generated by rimz {}. A read-only copy of the `reflect` consensus piece RimZ \
         ships: RimZ never reads this file, so edits change nothing and are overwritten. To \
         replace its wording for every team that lists `reflect`, copy this text to \
         `traits/reflect.md` in the RimZ home. -->\n\n{SHIPPED_REFLECT}",
        crate::build_id::VERSION
    )
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Consensus {
    BuiltIn,
    File(PathBuf),
}

/// Composed after the role's base prompt and fragments, in field order.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct TeamPrompt {
    pub consensus: Consensus,
    pub files: Vec<crate::config::PromptSource>,
}

impl TeamPrompt {
    /// The layer one role of `team` receives. Replacement is the only typed
    /// prompt channel, so a role without a base prompt receives none; an
    /// unstaged team has no pipeline for a consensus to govern.
    pub(super) fn for_role(team: &Team, role_has_base: bool) -> Option<Self> {
        (team.staged() && role_has_base).then(|| Self {
            consensus: team
                .consensus_file
                .clone()
                .map_or(Consensus::BuiltIn, Consensus::File),
            files: team.append_system_prompt_files.clone(),
        })
    }
}

/// Whether the team configures its layer explicitly, which makes an
/// undeliverable layer a refusal instead of a silent omission.
pub(super) fn declared(team: &Team) -> bool {
    team.consensus_file.is_some() || !team.append_system_prompt_files.is_empty()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn consensus_copies_write_once_and_repair_edits() {
        let home = tempfile::tempdir().unwrap();
        let paths = [
            consensus_copy_path(home.path()),
            reflect_copy_path(home.path()),
        ];
        assert_eq!(publish_consensus_copy(home.path()).unwrap(), paths);
        let texts = paths
            .clone()
            .map(|path| std::fs::read_to_string(path).unwrap());
        for (text, embedded) in texts.iter().zip([BUILT_IN_CONSENSUS, SHIPPED_REFLECT]) {
            assert!(text.starts_with("<!-- Generated by rimz "), "{text}");
            assert!(text.ends_with(embedded));
        }
        assert!(texts[1].contains("copy this text to `traits/reflect.md`"));
        assert!(publish_consensus_copy(home.path()).unwrap().is_empty());
        for (path, text) in paths.iter().zip(&texts) {
            std::fs::write(path, "edited").unwrap();
            assert_eq!(
                publish_consensus_copy(home.path()).unwrap(),
                std::slice::from_ref(path)
            );
            assert_eq!(&std::fs::read_to_string(path).unwrap(), text);
        }
    }

    #[test]
    fn reflection_lives_only_in_the_shipped_piece() {
        assert!(!BUILT_IN_CONSENSUS.to_lowercase().contains("reflect"));
        for text in [BUILT_IN_CONSENSUS, SHIPPED_REFLECT] {
            assert!(!text.contains("Skill(reflect)"));
        }
        assert!(SHIPPED_REFLECT.contains("Skill(rimz-reflect)"));
    }
}
